# Промпт ЭКСПРЕСС-ОЦЕНКИ — фото БЕЗ индикатора налёта.
#
# Два принципиальных отличия от основного промпта, оба намеренные:
# 1) НИКАКИХ ЧИСЕЛ. Без индикатора налёт не окрашен, измерять нечего. Если попросить
#    у модели проценты или балл, она их ВЫДУМАЕТ (проверено на реальных фото: модель
#    уверенно ставила 20-40% налёта чистым зубам). Поэтому экспресс-оценка возвращает
#    только качественные наблюдения, а точные метрики остаются за анализом с индикатором.
# 2) Схема ответа описана СЛОВАМИ, без заполненного примера. Заполненный пример модель
#    склонна копировать дословно на любое фото (этим болел GigaChat в основном промпте).
PROMPT_EXPRESS = """Ты — стоматологический ИИ-ассистент сервиса «Радуга Улыбок». Это режим ЭКСПРЕСС-ОЦЕНКИ: пациент прислал обычное фото зубов БЕЗ индикатора налёта.

ГЛАВНОЕ ОГРАНИЧЕНИЕ
Налёт на фото НЕ окрашен индикатором, поэтому измерить его площадь невозможно. Не оценивай количество налёта в процентах, не выставляй балл и вообще не называй никаких чисел. Описывай ТОЛЬКО то, что реально видно глазом на этом фото.

ФОРМАТ ОТВЕТА — строго ОДИН валидный JSON-объект без markdown, ровно с тремя полями:
- "is_valid": true или false (см. «Валидация фото»)
- "observations": массив из 2-4 строк. Каждая строка — одно короткое наблюдение о том, что видно на фото: общая чистота зубов, заметный мягкий налёт у линии дёсен, потемнения между зубами, зубной камень, покраснение или отёчность дёсен, состояние языка. Пиши о том, что действительно видишь, а не о том, что бывает обычно. Если зубы выглядят чистыми и ухоженными — так и напиши, не выдумывай проблемы.
- "recommendations": массив ровно из 3 строк. Практичные советы по уходу с конкретными действиями и инструментами (зубная нить, ирригатор, ёршики, техника Басса, электрическая щётка, ополаскиватель, чистка языка). Без общих фраз вроде «следите за гигиеной».

ВАЛИДАЦИЯ ФОТО
Верни is_valid=false и пустые массивы, если:
- на фото нет зубов или они плохо различимы
- качество слишком низкое (размыто, темно, снято слишком далеко)
- на фото посторонние объекты вместо зубов
Лучше честно вернуть is_valid=false, чем выдать недостоверную оценку.

ТОН
Спокойный, доброжелательный, без запугивания. Это ознакомительная оценка, а не приговор.

НЕЛЬЗЯ
- называть проценты, баллы, оценки по шкале и любые другие числа
- ставить медицинские диагнозы («кариес», «пародонтит», «гингивит» и т.п.) — это информационно-образовательный сервис, а не медицинская услуга
- утверждать, что оценка точная или окончательная
- вставлять markdown (```json, **жирный**)
- добавлять преамбулу типа «Вот анализ:»

ЯЗЫК
Все строковые поля на русском."""


class Command(BaseCommand):
    help = 'Инициализация настроек системы по умолчанию'

    def add_arguments(self, parser):
        parser.add_argument(
            '--reset-prompts',
            action='store_true',
            help='Перезаписать prompt_text/prompt_milk/prompt_mixed/prompt_permanent на дефолтные значения '
                 '(затирает текущие значения из админки — использовать осознанно).',
        )

    def handle(self, *args, **options):
        reset_prompts = options.get('reset_prompts', False)
        prompt_keys = {'prompt_text', 'prompt_milk', 'prompt_mixed', 'prompt_permanent',
                       'prompt_express'}
        defaults = {
            'initial_attempts': '3',
            # Бесплатные экспресс-оценки, которые получает новый аккаунт при регистрации.
            # Отдельный счётчик: не пересекается с балансом анализов с индикатором.
            'initial_express_attempts': '3',
            'prompt_text': PROMPT_BASE,
            'prompt_milk': PROMPT_MILK,
            'prompt_mixed': PROMPT_MIXED,
            'prompt_permanent': PROMPT_PERMANENT,
            'prompt_express': PROMPT_EXPRESS,
            'ai_provider': 'gemini',
            'ai_model': 'gemini-2.5-flash',
            # Отдельная сеть/модель для экспресс-оценки. Пусто = «как в основном
            # анализе»: экспресс идёт на общей сети, как было до разделения.
            # Задача у экспресса легче (описать словами, без цифр), поэтому на неё
            # можно поставить модель попроще, не трогая анализ с индикатором.
            'ai_provider_express': '',
            'ai_model_express': '',
            # Скрипт измерения налёта по пикселям красителя (анализ с индикатором).
            # true — проценты и балл меряет скрипт, нейросеть пишет только текст,
            #        в ЛК появляется фото с подсветкой зон налёта;
            # false — всё как раньше: проценты оценивает нейросеть, подсветки нет.
            # Если скрипт не находит зубы на фото, он сам отдаёт анализ нейросети.
            'cv_plaque_enabled': 'true',
            # ID счётчика Яндекс.Метрики. Пусто = аналитика выключена.
            # Клиент вставляет номер счётчика в админке (Настройки системы),
            # фронт подхватывает его публично — пересборка не нужна.
            'yandex_metrika_id': '',
            # Ссылка на анкету (Яндекс.Формы). Пусто = анкета не показывается.
            'survey_url': '',
            # Версия анкеты. Когда клиент меняет вопросы в форме и нажимает в админке
            # «Предложить анкету заново всем» — это значение увеличивается, и анкета
            # снова начинает предлагаться всем пользователям (в т.ч. прошедшим старую).
            'survey_version': '1',
        }
        for key, value in defaults.items():
            if reset_prompts and key in prompt_keys:
                SystemSettings.objects.update_or_create(key=key, defaults={'value': value})
                self.stdout.write(f'Перезаписан: {key}')
            else:
                _, created = SystemSettings.objects.get_or_create(key=key, defaults={'value': value})
                status = 'Создано' if created else 'Уже существует'
                self.stdout.write(f'{status}: {key}')

        # Предсоздаём 6 слотов правовых документов — пустыми. Клиент в админке
        # либо загрузит PDF, либо вставит HTML-текст в каждый слот.
        for slug, title in LegalDocument.SLUG_CHOICES:
            _, created = LegalDocument.objects.get_or_create(slug=slug)
            status = 'Создан' if created else 'Уже есть'
            self.stdout.write(f'{status} слот документа: {slug} ({title})')

        # Группа прав «Эксперт» (ограниченный администратор). Создаётся после
        # миграций, когда права моделей уже существуют.
        group = ensure_expert_group()
        self.stdout.write(f'Группа прав готова: {group.name} ({group.permissions.count()} прав)')

        self.stdout.write(self.style.SUCCESS('Настройки инициализированы'))
